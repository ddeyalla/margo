import { open } from "node:fs/promises";
import path from "node:path";
import { byChapter, sameAnchor, UNTITLED_SECTION } from "@/lib/shared/annotations";
import type { Anchor, Annotations, BookFormat, BookId, CardSet, Cue, LibraryBook, Note, VaultStatus } from "@/lib/shared/types";
import { readBookState, serialized, writeFileAtomic } from "./store";

/* The Obsidian mirror: one markdown file per book in NOTES_DIR, rewritten
   from the app's JSON after every highlight, note or card change. */

export interface VaultBook {
  id: BookId;
  title: string;
  author: string | null;
  format: BookFormat;
}

const GENERATED =
  "Generated by rigg learn from the highlights, notes and cards saved in the app. Don't edit: the app rewrites this file after every change.";

/* Shown at the top of the note, since Obsidian hides frontmatter in reading view. */
const GENERATED_CALLOUT = [
  "> [!info] Generated by rigg learn, don't edit",
  "> This file is rewritten from the book's highlights, notes and cards after every change, so edits made here are lost. Write your own notes in a separate file, and embed a highlight in it with `![[file name#^block id]]`.",
];

/** A title as a file name, without its extension: no characters that file systems or Obsidian links reject. */
export const safeFileName = (title: string, fallback: string): string => {
  const name = title
    .normalize("NFC")
    .replace(/[\u0000-\u001f\u007f]/g, "")
    .replace(/\s*:\s*/g, " - ")
    .replace(/[\\/*?"<>|#^[\]]/g, "")
    .replace(/\s+/g, " ")
    .replace(/^[\s.]+|[\s.]+$/g, "")
    .slice(0, 120)
    .trim();
  return name || fallback;
};

/** The book's note file name. */
export const vaultFileName = (title: string): string => `${safeFileName(title, "Untitled book")}.md`;

/** An Obsidian block id, so [[Book#^h-1a2b3c4d]] links to the passage. */
const blockId = (prefix: "h" | "n" | "c", id: string) => `${prefix}-${id.replace(/-/g, "").slice(0, 8).toLowerCase()}`;

interface Entry {
  anchor: Anchor;
  chapterTitle: string | null;
  createdAt: string;
  quote: string;
  blockId: string;
  notes: Note[];
  cues: Cue[];
}

const quoteLines = (quote: string, id: string): string[] => {
  const lines = quote
    .trim()
    .split("\n")
    .map((line) => (line.trim() ? `> ${line.trim()}` : ">"));
  lines[lines.length - 1] += ` ^${id}`;
  return lines;
};

/** A card as a list item; continuation lines are indented so multi-line answers stay in the item. */
const cueLines = (cue: Cue): string[] => {
  const indent = (text: string) => text.trim().replace(/\n/g, "\n  ");
  return [`- **Q:** ${indent(cue.question)}`, `  **A:** ${indent(cue.answer)}`];
};

/** YAML scalars are written as JSON strings, which YAML reads as double-quoted strings. */
const yaml = (value: string) => JSON.stringify(value);

/**
 * The note file: frontmatter, then one "## Chapter" section per chapter in
 * reading order. Each highlight is a quote ending in its block id, with its
 * notes and cards underneath. A note whose highlight was removed, or cards on
 * a passage with no highlight, keep their own quote.
 */
export const renderVault = (book: VaultBook, { highlights, notes, cardSets = [] }: Annotations & { cardSets?: CardSet[] }): string => {
  const highlightIds = new Set(highlights.map((h) => h.id));
  const attached = new Map<string, Note[]>();
  const standalone: Note[] = [];
  for (const note of [...notes].sort((a, b) => a.createdAt.localeCompare(b.createdAt))) {
    if (note.highlightId && highlightIds.has(note.highlightId)) {
      attached.set(note.highlightId, [...(attached.get(note.highlightId) ?? []), note]);
    } else {
      standalone.push(note);
    }
  }
  const entries: Entry[] = [
    ...highlights.map((h) => ({ ...h, blockId: blockId("h", h.id), notes: attached.get(h.id) ?? [], cues: [] as Cue[] })),
    ...standalone.map((n) => ({ ...n, blockId: blockId("n", n.id), notes: [n], cues: [] as Cue[] })),
  ];
  /* Questions that came from chapter quizzes are the app's, not cards the reader made: they stay out of the notes. */
  for (const entry of cardSets) {
    const cues = entry.cues.filter((cue) => !cue.origin);
    if (!cues.length) continue;
    const home = entries.find((candidate) => sameAnchor(candidate.anchor, entry.anchor));
    if (home) home.cues.push(...cues);
    else entries.push({ ...entry, blockId: blockId("c", entry.id), notes: [], cues });
  }
  const groups = byChapter(entries);

  const tags = new Map<string, string>();
  for (const note of groups.flatMap((group) => group.items.flatMap((entry) => entry.notes))) {
    for (const tag of note.tags) if (!tags.has(tag.toLowerCase())) tags.set(tag.toLowerCase(), tag);
  }

  const lines = [
    "---",
    /* First, so fileBookId finds it however long the title and author are. */
    `bookId: ${book.id}`,
    `title: ${yaml(book.title)}`,
    `author: ${yaml(book.author ?? "")}`,
    `format: ${book.format}`,
    ...(tags.size ? ["tags:", ...[...tags.values()].map((tag) => `  - ${yaml(tag)}`)] : ["tags: []"]),
    `generated: ${yaml(GENERATED)}`,
    "---",
    "",
    ...GENERATED_CALLOUT,
  ];
  for (const group of groups) {
    lines.push("", `## ${group.title?.replace(/\s+/g, " ") ?? UNTITLED_SECTION}`);
    for (const entry of group.items) {
      lines.push("", ...quoteLines(entry.quote, entry.blockId));
      for (const note of entry.notes) if (note.body.trim()) lines.push("", note.body.trim());
      if (entry.cues.length) lines.push("", "Cards:", "", ...entry.cues.flatMap(cueLines));
    }
  }
  return `${lines.join("\n")}\n`;
};

/** Older files put `bookId` after the title and author, so enough is read to reach it past a long pair. */
const HEAD_BYTES = 8192;

/** The `bookId` in a note file's frontmatter, or null when the file is missing, is someone else's note or has none. */
export const fileBookId = async (file: string): Promise<string | null> => {
  let handle;
  try {
    handle = await open(file, "r");
    const { buffer, bytesRead } = await handle.read(Buffer.alloc(HEAD_BYTES), 0, HEAD_BYTES, 0);
    const head = buffer.toString("utf8", 0, bytesRead);
    if (!/^---\r?\n/.test(head)) return null;
    const end = head.indexOf("\n---", 3);
    return (head.slice(0, end === -1 ? undefined : end).match(/^bookId: *(\S+)\s*$/m) ?? [])[1] ?? null;
  } catch {
    return null;
  } finally {
    await handle?.close();
  }
};

const exists = (file: string) => open(file, "r").then((handle) => handle.close().then(() => true), () => false);

const MAX_COPIES = 99;

/**
 * Where this book's note file goes: its title's name, or "Title (2).md", "Title (3).md" when that name holds a
 * file this book did not write, such as another book with the same title or a note of the reader's own. A file is
 * this book's when its frontmatter `bookId` is this book's id (every version has written it). The book keeps
 * the file it already has, wherever it sits in the sequence, and otherwise takes the first free name.
 */
export const vaultFilePath = async (notesDir: string, book: VaultBook): Promise<string> => {
  const base = vaultFileName(book.title).slice(0, -3);
  const names = [`${base}.md`, ...Array.from({ length: MAX_COPIES }, (_, i) => `${base} (${i + 2}).md`)];
  let free: string | null = null;
  for (const name of names) {
    const file = path.join(/*turbopackIgnore: true*/ notesDir, name);
    if ((await fileBookId(file)) === book.id) return file;
    if (free === null && !(await exists(file))) free = file;
  }
  if (free === null) throw new Error(`Every file name for "${base}" is taken by notes this app did not write.`);
  return free;
};

/** Rewrites the book's note file, creating NOTES_DIR if needed. Never overwrites a file this book did not write. A failure is reported, never thrown. */
export const writeVault = async (notesDir: string, book: VaultBook, annotations: Parameters<typeof renderVault>[1]): Promise<VaultStatus> => {
  try {
    /* One book at a time picks its name, so two books with the same title cannot both take a free one. */
    const file = await serialized(`vault-names:${notesDir}`, async () => {
      const target = await vaultFilePath(notesDir, book);
      await writeFileAtomic(target, renderVault(book, annotations));
      return target;
    });
    return { state: "written", file };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return { state: "failed", error: `The markdown copy could not be written to ${notesDir}. ${reason}` };
  }
};

/**
 * Rewrites the book's markdown copy from the saved JSON. Writes queue per
 * book and each reads the latest state when its turn comes, so the file
 * always ends up matching the last change.
 */
export const mirrorVault = (book: LibraryBook, dataDir: string, notesDir: string | null): Promise<VaultStatus> =>
  serialized(`vault:${book.id}`, async () => {
    if (!notesDir) return { state: "off" };
    const state = await readBookState(book.id, dataDir);
    const title = state.meta?.title ?? book.fileTitle;
    const author = state.meta?.author ?? book.fileAuthor;
    return writeVault(notesDir, { id: book.id, title, author, format: book.format }, state);
  });
