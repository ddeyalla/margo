import { mkdtemp, readdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { renderVault, vaultFileName, writeVault, type VaultBook } from "@/lib/server/vault";
import { addCards } from "@/lib/shared/cards";
import type { BookId, Highlight, Note } from "@/lib/shared/types";

const book: VaultBook = {
  id: "c7a9708c8427667f67560c06eade4af41a47400d" as BookId,
  title: "Generative AI Design Patterns: Solutions",
  author: "Valliappa Lakshmanan, Hannes Hapke",
  format: "pdf",
};

const highlight = (id: string, page: number, start: number, chapterTitle: string | null, quote: string): Highlight => ({
  id,
  anchor: { kind: "pdf", page, start, end: start + quote.length },
  quote,
  chapterTitle,
  color: "amber",
  createdAt: `2026-11-13T10:0${page % 10}:00.000Z`,
});

const highlights = [
  highlight("aaaaaaaa-1111-4111-8111-111111111111", 46, 200, "Pattern 1: Logits Masking", "Mask the logits that would break the format."),
  highlight("bbbbbbbb-2222-4222-8222-222222222222", 15, 40, "Chapter 1. Introduction", "A pattern names a problem.\n\nAnd its solution."),
  highlight("cccccccc-3333-4333-8333-333333333333", 15, 10, "Chapter 1. Introduction", "Design patterns."),
];

const note = (id: string, fields: Partial<Note>): Note => ({
  id,
  anchor: { kind: "pdf", page: 15, start: 40, end: 70 },
  quote: "A pattern names a problem.",
  chapterTitle: "Chapter 1. Introduction",
  highlightId: null,
  body: "",
  tags: [],
  createdAt: "2026-11-13T11:00:00.000Z",
  updatedAt: "2026-11-13T11:00:00.000Z",
  ...fields,
});

const notes = [
  note("dddddddd-4444-4444-8444-444444444444", {
    highlightId: "bbbbbbbb-2222-4222-8222-222222222222",
    body: "Like a recipe card. #patterns #design",
    tags: ["patterns", "design"],
  }),
  note("eeeeeeee-5555-4555-8555-555555555555", {
    anchor: { kind: "pdf", page: 50, start: 5, end: 30 },
    quote: "Its highlight was removed.",
    chapterTitle: "Pattern 2: Grammar",
    body: "- still here\n- **kept** #Patterns",
    tags: ["Patterns"],
  }),
];

describe("the Obsidian note file", () => {
  it("writes frontmatter, then chapters in reading order with block ids and notes", () => {
    expect(renderVault(book, { highlights, notes })).toBe(
      [
        "---",
        "bookId: c7a9708c8427667f67560c06eade4af41a47400d",
        'title: "Generative AI Design Patterns: Solutions"',
        'author: "Valliappa Lakshmanan, Hannes Hapke"',
        "format: pdf",
        "tags:",
        '  - "patterns"',
        '  - "design"',
        'generated: "Generated by rigg learn from the highlights, notes and cards saved in the app. Don\'t edit: the app rewrites this file after every change."',
        "---",
        "",
        "> [!info] Generated by rigg learn, don't edit",
        "> This file is rewritten from the book's highlights, notes and cards after every change, so edits made here are lost. Write your own notes in a separate file, and embed a highlight in it with `![[file name#^block id]]`.",
        "",
        "## Chapter 1. Introduction",
        "",
        "> Design patterns. ^h-cccccccc",
        "",
        "> A pattern names a problem.",
        ">",
        "> And its solution. ^h-bbbbbbbb",
        "",
        "Like a recipe card. #patterns #design",
        "",
        "## Pattern 1: Logits Masking",
        "",
        "> Mask the logits that would break the format. ^h-aaaaaaaa",
        "",
        "## Pattern 2: Grammar",
        "",
        "> Its highlight was removed. ^n-eeeeeeee",
        "",
        "- still here",
        "- **kept** #Patterns",
        "",
      ].join("\n"),
    );
  });

  it("writes only the frontmatter and the don't-edit header for a book with nothing marked, and names missing chapters", () => {
    const empty = renderVault({ ...book, author: null, format: "epub" }, { highlights: [], notes: [] });
    expect(empty).toContain('author: ""\nformat: epub\n');
    expect(empty).toContain("tags: []\n");
    expect(empty).toMatch(/---\n\n> \[!info\] Generated by rigg learn, don't edit\n> [^\n]+\n$/);
    const loose = renderVault(book, { highlights: [highlight("ffffffff-6666-4666-8666-666666666666", 2, 0, null, "Front matter.")], notes: [] });
    expect(loose).toContain("## Untitled section\n\n> Front matter. ^h-ffffffff\n");
  });

  it("writes cards under their highlight, or under their own quote when the passage has none", () => {
    let n = 0;
    const id = () => `9999999${++n}-0000-4000-8000-000000000000`;
    const now = new Date("2026-11-13T12:00:00Z");
    const onHighlight = addCards([], { anchor: highlights[2].anchor, quote: "Design patterns.", chapterTitle: "Chapter 1. Introduction", fact: "F", cards: [{ question: "What is a design pattern?", answer: "A named problem\nand its solution." }] }, now, id).sets;
    const alone = addCards(onHighlight, { anchor: { kind: "pdf", page: 60, start: 0, end: 9 }, quote: "No mark.", chapterTitle: "Pattern 3", fact: "F", cards: [{ question: "Q?", answer: "A." }] }, now, id).sets;
    const text = renderVault(book, { highlights, notes, cardSets: alone });
    expect(text).toContain("> Design patterns. ^h-cccccccc\n\nCards:\n\n- **Q:** What is a design pattern?\n  **A:** A named problem\n  and its solution.\n");
    expect(text).toContain(`## Pattern 3\n\n> No mark. ^c-${alone[1].id.slice(0, 8)}\n\nCards:\n\n- **Q:** Q?\n  **A:** A.\n`);
  });

  it("names the file after the title, without characters Obsidian or the file system reject", () => {
    expect(vaultFileName("Generative AI Design Patterns: Solutions")).toBe("Generative AI Design Patterns - Solutions.md");
    expect(vaultFileName('C# / F#? [Notes] "1" <a|b> ^x')).toBe("C F Notes 1 ab x.md");
    expect(vaultFileName("  ...  ")).toBe("Untitled book.md");
  });

  it("creates a missing notes folder and leaves no temp file behind", async () => {
    const notesDir = path.join(await mkdtemp(path.join(tmpdir(), "rigg-learn-vault-")), "Reading", "Books");
    const status = await writeVault(notesDir, book, { highlights, notes });
    expect(status).toEqual({ state: "written", file: path.join(notesDir, "Generative AI Design Patterns - Solutions.md") });
    expect(await readdir(notesDir)).toEqual(["Generative AI Design Patterns - Solutions.md"]);
    expect(await readFile(path.join(notesDir, "Generative AI Design Patterns - Solutions.md"), "utf8")).toBe(
      renderVault(book, { highlights, notes }),
    );
  });

  it("never overwrites a file this book did not write, and keeps the name it took", async () => {
    const notesDir = await mkdtemp(path.join(tmpdir(), "rigg-learn-vault-"));
    const mine = path.join(notesDir, "Generative AI Design Patterns - Solutions.md");
    await writeFile(mine, "My own note, no frontmatter.\n");
    const first = await writeVault(notesDir, book, { highlights, notes });
    expect(first).toEqual({ state: "written", file: path.join(notesDir, "Generative AI Design Patterns - Solutions (2).md") });
    expect(await readFile(mine, "utf8")).toBe("My own note, no frontmatter.\n");

    /* Another book with the same title goes to the next free name; the first keeps its file on every later write. */
    const other = { ...book, id: "d".repeat(40) as BookId };
    const second = await writeVault(notesDir, other, { highlights: [], notes: [] });
    expect(second).toEqual({ state: "written", file: path.join(notesDir, "Generative AI Design Patterns - Solutions (3).md") });
    expect(await writeVault(notesDir, book, { highlights, notes })).toEqual(first);
    expect(await readFile(mine, "utf8")).toBe("My own note, no frontmatter.\n");

    /* A book whose plain-named file is its own keeps writing there. */
    await writeFile(mine, renderVault(other, { highlights: [], notes: [] }));
    expect(await writeVault(notesDir, other, { highlights: [], notes: [] })).toEqual({ state: "written", file: mine });
  });

  it("recognises its own file however long the title and author are", async () => {
    const notesDir = await mkdtemp(path.join(tmpdir(), "rigg-learn-vault-"));
    const long = { ...book, title: `A Very Long Title ${"word ".repeat(1500)}`, author: "Someone ".repeat(500) };
    const first = await writeVault(notesDir, long, { highlights, notes });
    expect(await writeVault(notesDir, long, { highlights, notes })).toEqual(first);
    expect(await readdir(notesDir)).toHaveLength(1);
  });

  it("still recognises a file from before bookId came first", async () => {
    const notesDir = await mkdtemp(path.join(tmpdir(), "rigg-learn-vault-"));
    const long = { ...book, title: `Older Long Title ${"word ".repeat(500)}` };
    const [open, idLine, ...rest] = renderVault(long, { highlights, notes }).split("\n");
    const formatAt = rest.findIndex((line) => line.startsWith("format: "));
    const older = [open, ...rest.slice(0, formatAt + 1), idLine, ...rest.slice(formatAt + 1)].join("\n");
    expect(older.indexOf("bookId:")).toBeGreaterThan(2048);
    const file = path.join(notesDir, vaultFileName(long.title));
    await writeFile(file, older);
    expect(await writeVault(notesDir, long, { highlights, notes })).toEqual({ state: "written", file });
  });

  it("reports a folder it cannot create instead of throwing", async () => {
    const base = await mkdtemp(path.join(tmpdir(), "rigg-learn-vault-"));
    await writeFile(path.join(base, "not-a-folder"), "");
    const status = await writeVault(path.join(base, "not-a-folder", "Notes"), book, { highlights, notes });
    expect(status.state).toBe("failed");
  });
});
